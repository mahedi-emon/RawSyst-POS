-- California's published sales tax rates, from CDTFA's own quarterly file.
--
-- 0109 seeded California's 7.25% statewide share alone and left it
-- deliberately unverified, because a sale resolving only that rate would
-- undercharge wherever a district applies -- which is most of the state. This
-- is the missing half: the 541 locations CDTFA publishes, each with the share
-- levied on top of the state's.
--
-- Source: California Department of Tax and Fee Administration, "California
-- City & County Sales & Use Tax Rates", the file SalesTaxRates07-01-26.xlsx
-- linked from https://www.cdtfa.ca.gov/taxes-and-fees/sales-use-tax-rates.htm
-- and effective 1 July 2026. Downloaded and converted on 2026-09-04; the
-- quarter after it (10-01-26) is not published yet.
--
-- # These are shares, not the rates CDTFA prints
--
-- CDTFA publishes a COMBINED rate per location: Alameda reads 10.75%, and
-- that figure already contains the statewide 7.25%. This product sums a
-- jurisdiction chain instead, so storing 10.75% under a state already holding
-- 7.25% would charge 18%. Each row below is therefore the published combined
-- rate LESS the statewide rate -- Alameda 0.035 -- and the chain adds back to
-- exactly what CDTFA printed, which is the number a shop is audited against.
--
-- The arithmetic is done by cmd/cdtfaimport, which reads the authority's file
-- and refuses rather than guessing if any location falls below the statewide
-- base. Next quarter's file goes through the same tool and is applied through
-- POST /api/v1/platform/jurisdictions/import, which supersedes these rows by
-- date rather than editing them.
--
-- # Still unverified, on purpose
--
-- verified_on is NULL on every row. The figures are the authority's own, but
-- nobody has yet put their name to the conversion, and the product refuses an
-- unverified rate rather than charging it. So this does not let a Californian
-- shop trade -- it means the operator confirming these rates is checking 541
-- rows that are already filled in, instead of typing them.
--
-- # Five counties are absent, and that is what CDTFA says
--
-- Del Norte, Kern, Monterey, Santa Cruz and Yuba publish no county-wide
-- figure: their row carries an empty rate and a note directing the reader to
-- the city or the unincorporated area. Each of those appears here as
-- "<name> County Unincorporated Area" plus its cities. A county-wide rate
-- invented for them would undercharge every sale in them.

