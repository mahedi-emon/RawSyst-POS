-- The locations themselves, hung off California rather than off their county:
-- CDTFA's city figure already includes any county district applying there, so
-- a city nested under its county would count that district twice.
INSERT INTO tax_jurisdiction (parent_id, country, level, code, name)
SELECT ca.id, 'us', l.level, l.code, l.name
FROM cdtfa_load l
CROSS JOIN (
  SELECT id FROM tax_jurisdiction
  WHERE country = 'us' AND level = 'state' AND code = 'CA'
) ca
ON CONFLICT (country, level, code) DO NOTHING;

-- One rate per location. California's own 7.25% row is untouched: it has been
-- in force since 2017 and this schedule does not change it, and a second row
-- for the same date range would fail tax_rate_no_overlap anyway.
INSERT INTO tax_jurisdiction_rate
  (jurisdiction_id, treatment, rate, effective_from,
   source_authority, source_document, source_url, notes)
SELECT j.id, 'taxable', l.rate, DATE '2026-07-01',
       'cdtfa',
       'CDTFA California City & County Sales & Use Tax Rates, effective '
       'July 1, 2026 (SalesTaxRates07-01-26.xlsx)',
       'https://www.cdtfa.ca.gov/taxes-and-fees/sales-use-tax-rates.htm',
       'This location''s own share: the combined rate CDTFA publishes for it '
       'less the statewide 7.25%, so the jurisdiction chain sums back to the '
       'published figure. Converted from the authority''s file by '
       'cmd/cdtfaimport on 2026-09-04. Unverified: nobody has yet confirmed '
       'the conversion against the published page.'
FROM cdtfa_load l
JOIN tax_jurisdiction j
  ON j.country = 'us' AND j.level = l.level AND j.code = l.code
ON CONFLICT DO NOTHING;
